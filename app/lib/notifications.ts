import { Resend } from "resend";
import { prisma } from "../prisma";

const resend = new Resend(
  process.env.RESEND_API_KEY
);

export async function deliverEmailNotification(
  notificationId: string
) {
  const notification =
    await prisma.notification.findUnique({
      where: {
        id: notificationId,
      },
      include: {
        user: true,
      },
    });

  if (!notification) {
    throw new Error("Notification not found.");
  }

  if (notification.channel !== "EMAIL") {
    throw new Error(
      "Notification is not configured for email."
    );
  }

  if (!notification.user.email) {
    throw new Error(
      "User does not have an email address."
    );
  }

  if (notification.status === "SENT") {
    return {
      success: true,
      status: "ALREADY_SENT",
      notificationId,
    };
  }

  const fromEmail =
    process.env.RESEND_FROM_EMAIL;

  if (!fromEmail) {
    throw new Error(
      "RESEND_FROM_EMAIL is not configured."
    );
  }

  const recipientEmail =
  process.env.NODE_ENV === "development"
    ? process.env.RESEND_TEST_RECIPIENT
    : notification.user.email;

if (!recipientEmail) {
  throw new Error(
    "No email recipient is configured."
  );
}

  const { data, error } =
    await resend.emails.send({
      from: `AZA CFO <${fromEmail}>`,
      to: [recipientEmail],
      subject: notification.title,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 32px; color: #18181b;">
          <h1 style="margin-bottom: 24px;">
            AZA Daily CFO Brief
          </h1>

          <p style="white-space: pre-line; line-height: 1.7;">
            ${notification.message}
          </p>

          <hr style="margin: 32px 0; border: 0; border-top: 1px solid #e4e4e7;" />

          <p style="font-size: 13px; color: #71717a;">
            This financial brief was generated by your AZA AI CFO.
          </p>
        </div>
      `,
    });

if (error) {
  console.error("RESEND_EMAIL_ERROR:", error);

  await prisma.notification.update({
    where: {
      id: notificationId,
    },
    data: {
      status: "FAILED",
    },
  });

  throw new Error(
    `Resend error: ${JSON.stringify(error)}`
  );
}
  const updatedNotification =
    await prisma.notification.update({
      where: {
        id: notificationId,
      },
      data: {
        status: "SENT",
        sentAt: new Date(),
      },
    });

  return {
    success: true,
    status: "SENT",
    notificationId,
    providerMessageId: data?.id ?? null,
    sentAt: updatedNotification.sentAt,
  };
}