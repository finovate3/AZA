import { NextResponse } from "next/server";
import { Resend } from "resend";
import { prisma } from "../../../prisma";

const resend = new Resend(process.env.RESEND_API_KEY);

export async function POST(request: Request) {
  try {
    const body = await request.json();

    const notificationId = body.notificationId;

    if (!notificationId) {
      return NextResponse.json(
        {
          error: "notificationId is required.",
        },
        { status: 400 }
      );
    }

    const notification =
      await prisma.notification.findUnique({
        where: {
          id: notificationId,
        },
        include: {
          user: true,
        },
      });

    if (!notification) {
      return NextResponse.json(
        {
          error: "Notification not found.",
        },
        { status: 404 }
      );
    }

    if (notification.channel !== "EMAIL") {
      return NextResponse.json(
        {
          error: "This notification is not an email notification.",
        },
        { status: 400 }
      );
    }

    if (!notification.user.email) {
      return NextResponse.json(
        {
          error: "User does not have an email address.",
        },
        { status: 400 }
      );
    }

    if (notification.status === "SENT") {
      return NextResponse.json({
        success: true,
        status: "ALREADY_SENT",
        notificationId: notification.id,
      });
    }

    const fromEmail =
      process.env.RESEND_FROM_EMAIL;

    if (!fromEmail) {
      return NextResponse.json(
        {
          error: "RESEND_FROM_EMAIL is not configured.",
        },
        { status: 500 }
      );
    }

    const { data, error } =
      await resend.emails.send({
        from: `AZA CFO <${fromEmail}>`,
        to: [notification.user.email],
        subject: notification.title,
        html: `
          <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 32px; color: #18181b;">
            <h1 style="margin-bottom: 24px;">
              AZA Daily CFO Brief
            </h1>

            <p style="white-space: pre-line; line-height: 1.7;">
              ${notification.message}
            </p>

            <hr style="margin: 32px 0; border: 0; border-top: 1px solid #e4e4e7;" />

            <p style="font-size: 13px; color: #71717a;">
              This financial brief was generated by your AZA AI CFO.
            </p>
          </div>
        `,
      });

    if (error) {
      await prisma.notification.update({
        where: {
          id: notification.id,
        },
        data: {
          status: "FAILED",
        },
      });

      return NextResponse.json(
        {
          success: false,
          notificationId: notification.id,
          error,
        },
        { status: 502 }
      );
    }

    const updatedNotification =
      await prisma.notification.update({
        where: {
          id: notification.id,
        },
        data: {
          status: "SENT",
          sentAt: new Date(),
        },
      });

    return NextResponse.json({
      success: true,
      status: "SENT",
      notificationId: updatedNotification.id,
      emailId: data?.id ?? null,
      sentAt: updatedNotification.sentAt,
    });
  } catch (error) {
    console.error(
      "AI_CFO_EMAIL_DELIVERY_ERROR:",
      error
    );

   return NextResponse.json(
  {
    success: false,
    provider: "resend",
    error:
      error instanceof Error
        ? error.message
        : String(error),
  },
  { status: 502 }
);
  }
}